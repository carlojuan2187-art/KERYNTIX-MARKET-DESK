function normalize(value: string): string {
  return value.replace(/\s+/g, " ").trim();
}

export function getStoredLanguage(): Language {
  try {
    return window.localStorage.getItem("ftrade.language") === "es" ? "es" : "en";
  } catch {
    return "en";
  }
}

export function getIntlLocale(language: Language = getStoredLanguage()): string {
  return language === "es" ? "es-PR" : "en-US";
}

export function translate(value: string | null | undefined, language: Language = getStoredLanguage()): string {
  if (typeof value !== "string" || !value || language === "es") return value || "";
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const key = normalize(value);
  const exact = EN[key];
  if (exact) return `${leading}${exact}${trailing}`;
  // Common dynamic messages from the API and relative-time formatter.
  let match = key.match(/^Hace (\d+) (s|seg|segundos?|min|mins?|h|hrs?|horas?|d|días?)$/i);
  if (match) {
    const unit = match[2].toLowerCase();
    const label = ["s", "seg", "segundo", "segundos"].includes(unit) ? "sec ago"
      : ["min", "mins", "minuto", "minutos"].includes(unit) ? "min ago"
      : ["h", "hr", "hrs", "hora", "horas"].includes(unit) ? "hr ago" : "days ago";
    return `${Number(match[1])} ${label}`;
  }
  match = key.match(/^Hace (\d+) h (\d+) min$/i);
  if (match) return `${Number(match[1])} hr ${Number(match[2])} min ago`;
  match = key.match(/^Finaliza el (.+)$/);
  if (match) return `Ends on ${match[1]}`;
  match = key.match(/^Notificaciones, (\d+) sin leer$/i);
  if (match) return `Notifications, ${match[1]} unread`;
  if (key.startsWith("AVISO ·")) return key.replace("AVISO ·", "ALERT ·");
  if (key.startsWith("Nuevo setup")) return key.replace("Nuevo setup", "New setup");
  return value;
}

export function t(value: string, language: Language = getStoredLanguage()): string {
  return translate(value, language);
}
